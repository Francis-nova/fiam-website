// Generates src/components/icons.generated.ts from the Iconify JSON packages, so the
// site ships inline SVGs instead of fetching icons from api.iconify.design at runtime.
// Add a name to ICONS and run `npm run icons`.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { getIconData, iconToSVG } from '@iconify/utils';

const require = createRequire(import.meta.url);

const ICONS = [
  'cryptocurrency-color:btc',
  'cryptocurrency-color:eth',
  'cryptocurrency-color:usdt',
  'logos:google-play-icon',
  'mdi:apple',
  'ri:instagram-line',
  'ri:linkedin-fill',
  'ri:twitter-x-fill',
  'solar:add-circle-linear',
  'solar:alt-arrow-right-linear',
  'solar:arrow-down-bold',
  'solar:arrow-left-linear',
  'solar:arrow-right-linear',
  'solar:arrow-up-bold',
  'solar:bell-bing-bold',
  'solar:bill-list-bold',
  'solar:card-recive-bold',
  'solar:case-round-bold',
  'solar:chat-round-dots-bold',
  'solar:check-circle-bold',
  'solar:clipboard-check-bold',
  'solar:close-circle-linear',
  'solar:danger-triangle-bold',
  'solar:eye-scan-bold',
  'solar:hamburger-menu-linear',
  'solar:history-bold',
  'solar:letter-bold',
  'solar:lock-keyhole-bold',
  'solar:magnifer-linear',
  'solar:minus-circle-linear',
  'solar:pen-new-square-bold',
  'solar:plain-bold',
  'solar:qr-code-bold',
  'solar:shield-check-bold',
  'solar:shield-keyhole-bold',
  'solar:shield-warning-bold',
  'solar:snowflake-bold',
  'solar:square-transfer-horizontal-bold',
  'solar:user-id-bold',
  'solar:user-plus-bold',
  'solar:wallet-money-bold',
];

const sets = {};
const out = {};
for (const name of ICONS) {
  const [prefix, icon] = name.split(':');
  sets[prefix] ??= JSON.parse(readFileSync(require.resolve(`@iconify-json/${prefix}/icons.json`), 'utf8'));
  const data = getIconData(sets[prefix], icon);
  if (!data) throw new Error(`Unknown icon: ${name}`);
  const { attributes, body } = iconToSVG(data, { height: '1em' });
  out[name] = { viewBox: attributes.viewBox, width: attributes.width, body };
}

const file = `// GENERATED by scripts/build-icons.mjs — do not edit by hand.
export const icons = ${JSON.stringify(out, null, 2)} as const;

export type IconName = keyof typeof icons;
`;
writeFileSync(new URL('../src/components/icons.generated.ts', import.meta.url), file);
console.log(`Wrote ${ICONS.length} icons`);
